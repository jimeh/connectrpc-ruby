# frozen_string_literal: true

require "rubygems"

# Lowest-allowed dependency lane, selected with CONNECTRPC_DEPENDENCY_FLOORS=1.
#
# Real Gemfiles, Appraisals and generated lane Gemfiles carry no floors logic.
# Floors mode writes an ignored wrapper next to the owning Gemfile, so relative
# `path:`/`gemspec` options keep their meaning and Bundler derives a separate
# ignored lock from the wrapper name. The wrapper evaluates the original Gemfile
# through this helper, which pins every third-party runtime dependency of the
# loaded connectrpc gemspecs to the lowest version its requirement admits.
# A launcher may add floors-only constraints for transitive gems the floors
# cannot coexist with; they never appear in the real Gemfiles.
module DependencyFloors
  # `bundle exec` loads this file through the wrapper before it runs as the checker script.
  ROOT = File.expand_path("..", __dir__) unless const_defined?(:ROOT)
  ENVIRONMENT = "CONNECTRPC_DEPENDENCY_FLOORS" unless const_defined?(:ENVIRONMENT)

  module_function

  def enabled?
    ENV[ENVIRONMENT] == "1"
  end

  # The Gemfile a bundle process should use: the original, or its generated
  # floors wrapper in floors mode. `constraints` maps gem names to extra
  # requirements applied only in floors mode; its launcher documents why.
  def gemfile(original, constraints: {})
    return original unless enabled?

    wrapper = wrapper_path(original)
    helper = File.join(ROOT, "scripts/dependency_floors.rb")
    File.write(wrapper, <<~RUBY)
      # frozen_string_literal: true

      # Generated by scripts/dependency_floors.rb for #{ENVIRONMENT}=1. Do not edit or commit.
      require #{helper.dump}
      DependencyFloors.evaluate(self, #{original.dump}, constraints: #{constraints.inspect})
    RUBY
    wrapper
  end

  def wrapper_path(original)
    directory = File.dirname(original)
    name = File.basename(original)
    floors = name == "Gemfile" ? "Gemfile.floors" : name.sub(/\.gemfile\z/, ".floors.gemfile")
    raise "Cannot derive a floors wrapper name for #{original}" if floors == name

    File.join(directory, floors)
  end

  def gemspec_path(name)
    name == "connectrpc" ? File.join(ROOT, "connectrpc.gemspec") : File.join(ROOT, "gems", name, "#{name}.gemspec")
  end

  def local?(name)
    name == "connectrpc" || name.start_with?("connectrpc-")
  end

  def specification(name)
    path = gemspec_path(name)
    Dir.chdir(File.dirname(path)) { Gem::Specification.load(path) } || raise("Cannot load #{path}")
  end

  # Lowest version a requirement admits: `>= 3.3` -> 3.3, `~> 0.105.0` -> 0.105.0.
  def floor(requirement)
    lower = requirement.requirements.filter_map { |operator, version| version if %w[>= ~> =].include?(operator) }
    raise "No inclusive lower bound in #{requirement}" if lower.empty?

    lower.max
  end

  # The named local packages plus their local runtime closure.
  def local_specifications(names)
    pending = names.select { |name| local?(name) }
    loaded = {}
    until pending.empty?
      name = pending.shift
      next if loaded.key?(name)

      loaded[name] = specification(name)
      pending.concat(loaded[name].runtime_dependencies.map(&:name).select { |dependency| local?(dependency) })
    end
    loaded.values
  end

  # Third-party runtime floors of the named local packages and their local runtime closure.
  def floors(names)
    dependencies = local_specifications(names).flat_map(&:runtime_dependencies).reject { |entry| local?(entry.name) }
    dependencies.group_by(&:name).sort.to_h { |name, entries| [name, shared_floor(name, entries.map(&:requirement))] }
  end

  # The highest individual floor, which every package's requirement must admit.
  def shared_floor(name, requirements)
    version = requirements.map { |requirement| floor(requirement) }.max
    return version if requirements.all? { |requirement| requirement.satisfied_by?(version) }

    raise "Floor #{name} #{version} conflicts with #{requirements.join('; ')}"
  end

  # Replaces the requirement of a floor-managed `gem` declaration and adds any
  # floors-only constraint, keeping its options.
  module Declarations
    def gem(name, *args)
      version = @connectrpc_floors.fetch(name, nil)
      constraint = @connectrpc_constraints.fetch(name, nil)
      return super unless version || constraint

      options = args.last.is_a?(Hash) ? args.pop : {}
      requirements = version ? ["= #{version}"] : args
      super(name, *requirements, *constraint, options)
    end
  end

  # Floors of the packages an unmodified Gemfile declares.
  def gemfile_floors(original)
    probe = Bundler::Dsl.new
    probe.eval_gemfile(original)
    floors(probe.dependencies.map(&:name))
  end

  # Called from a generated wrapper inside Bundler's Gemfile DSL.
  def evaluate(dsl, original, constraints: {})
    pins = gemfile_floors(original)
    dsl.instance_variable_set(:@connectrpc_floors, pins)
    dsl.instance_variable_set(:@connectrpc_constraints, constraints)
    dsl.extend(Declarations)
    dsl.eval_gemfile(original)
    declared = dsl.dependencies.map(&:name)
    (pins.keys | constraints.keys).each { |name| dsl.gem(name, require: false) unless declared.include?(name) }
  end

  # Checks a loaded floors bundle resolved every floor exactly and prints them.
  def check!(specs)
    resolved = specs.to_h { |spec| [spec.name, spec.version] }
    pins = floors(resolved.keys)
    raise "No floor-managed dependencies in this bundle" if pins.empty?

    pins.each { |name, version| check_floor!(name, version, resolved.fetch(name, nil)) }
  end

  def check_floor!(name, version, actual)
    raise "Floor dependency #{name} is missing from the bundle" unless actual
    raise "Floor drift: #{name} resolved #{actual}, expected #{version}" unless actual == version

    puts "floor #{name} #{actual}"
  end
end

if $PROGRAM_NAME == __FILE__
  require "bundler"
  abort "Run with #{DependencyFloors::ENVIRONMENT}=1 under the floors bundle" unless DependencyFloors.enabled?
  abort "Not running under a floors wrapper: #{ENV.fetch('BUNDLE_GEMFILE', nil)}" unless
    File.basename(Bundler.default_gemfile.to_s).include?(".floors")
  DependencyFloors.check!(Bundler.load.specs)
  puts "Lowest-allowed bundle #{Bundler.default_gemfile} resolved every declared floor"
end
