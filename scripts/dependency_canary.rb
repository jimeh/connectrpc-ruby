# frozen_string_literal: true

require "rubygems"
require_relative "dependency_floors"

# Pins-lifted canary lane, selected with CONNECTRPC_DEPENDENCY_CANARY=1.
#
# Like the floors lane, canary mode writes an ignored wrapper (`Gemfile.canary`)
# beside the owning Gemfile, so Bundler derives a separate ignored lock. A
# Gemfile cannot widen a gemspec requirement, so the wrapper first prepends
# Lifting onto Gem::Specification: while canary mode is on, a local connectrpc
# package's third-party patch pin (one `~> x.y.z` requirement) becomes
# `>= x.y.z, < next major` (`< 1` for 0.x). Every later gemspec load in that
# process, including path gems Bundler loads lazily and `bundle exec` children
# that evaluate the wrapper again, sees the lifted requirement. The bundle uses
# its own BUNDLE_PATH and BUNDLE_USER_HOME, so no normal cache sees it.
#
# Run under the canary bundle, this file prints the report below.
# scripts/canary_driver.rb drives the lane around it.
module DependencyCanary
  # `bundle exec` loads this file through the wrapper before it runs as the script.
  ROOT = File.expand_path("..", __dir__) unless const_defined?(:ROOT, false)
  ENVIRONMENT = "CONNECTRPC_DEPENDENCY_CANARY" unless const_defined?(:ENVIRONMENT, false)
  # Launcher commands that never build or install package archives.
  COMMANDS = %w[setup exec test canary].freeze unless const_defined?(:COMMANDS, false)
  # Reported with each run so a failure names the stack it resolved.
  unless const_defined?(:STACK, false)
    STACK = %w[async async-http protocol-http protocol-http1 protocol-http2 io-stream io-endpoint falcon].freeze
  end
  Lift = Struct.new(:package, :name, :original, :lifted) unless const_defined?(:Lift, false)

  module_function

  def enabled?
    ENV[ENVIRONMENT] == "1"
  end

  def reject_floors!
    return unless DependencyFloors.enabled?

    raise "#{ENVIRONMENT}=1 and #{DependencyFloors::ENVIRONMENT}=1 cannot be combined"
  end

  # The Gemfile a bundle process should use: the original, or its generated
  # canary wrapper in canary mode.
  def gemfile(original)
    return original unless enabled?

    reject_floors!
    wrapper = wrapper_path(original)
    helper = File.join(ROOT, "scripts/dependency_canary.rb")
    File.write(wrapper, <<~RUBY)
      # frozen_string_literal: true

      # Generated by scripts/dependency_canary.rb for #{ENVIRONMENT}=1. Do not edit or commit.
      require #{helper.dump}
      DependencyCanary.evaluate(self, #{original.dump})
    RUBY
    wrapper
  end

  def wrapper_path(original)
    raise "Cannot derive a canary wrapper name for #{original}" unless File.basename(original) == "Gemfile"

    File.join(File.dirname(original), "Gemfile.canary")
  end

  # Bundle install and Bundler user state (including its index cache) for a
  # package's vendor directory, kept apart from the normal bundle in canary mode.
  def bundle_settings(vendor)
    base = enabled? ? File.join(vendor, "canary") : vendor
    { "BUNDLE_PATH" => File.join(base, "bundle"), "BUNDLE_USER_HOME" => File.join(base, "bundler") }
  end

  # Rejects a launcher command outside the lane, or canary and floors mode together.
  def allow!(command)
    return unless enabled?

    reject_floors!
    return if COMMANDS.include?(command)

    raise "#{command} is not part of the pins-lifted canary lane (#{COMMANDS.join('|')})"
  end

  # Called from a generated wrapper inside Bundler's Gemfile DSL.
  def evaluate(dsl, original)
    reject_floors!
    raise "#{ENVIRONMENT}=1 is required to evaluate a canary wrapper" unless enabled?

    Gem::Specification.prepend(Lifting) unless Gem::Specification.ancestors.include?(Lifting)
    dsl.eval_gemfile(original)
  end

  # `~> x.y.z` becomes `>= x.y.z, < x+1` (`< 1` for 0.x); anything else is not a patch pin.
  def lift(requirement)
    return unless requirement.requirements.size == 1

    operator, version = requirement.requirements.first
    segments = version.segments
    return unless operator == "~>" && segments.size == 3 && segments.all?(Integer)

    Gem::Requirement.new(">= #{version}", "< #{segments.first.zero? ? 1 : segments.first + 1}")
  end

  # Lifted requirements for one declaration, recording the lift, or nil to keep it.
  def lift_declaration(package, name, requirements)
    package = package.to_s
    name = name.to_s
    return unless enabled? && DependencyFloors.local?(package) && !DependencyFloors.local?(name)

    original = Gem::Requirement.new(*requirements.flatten)
    lifted = lift(original) or return
    lifts[[package, name]] = Lift.new(package, name, original, lifted)
    lifted.as_list
  end

  def lifts
    @lifts ||= {}
  end

  def append_summary(markdown)
    path = ENV.fetch("GITHUB_STEP_SUMMARY", nil)
    File.write(path, "#{markdown}\n", mode: "a") if path && !path.empty?
  end

  # Prepended onto Gem::Specification by the canary wrapper.
  module Lifting
    def add_dependency(gem, *requirements)
      lifted = DependencyCanary.lift_declaration(name, gem, requirements)
      lifted ? super(gem, *lifted) : super
    end
  end

  # What a loaded canary bundle resolved for each lifted dependency.
  module Report
    unless const_defined?(:STACK_HEADING, false)
      STACK_HEADING = "Newest eligible socketry stack after the 3-day cooldown"
    end

    module_function

    # Each lift with its resolved version and whether that is beyond the
    # original pin. `resolved` maps gem names to versions; `locked` maps
    # [package, gem] to the requirement the canary lock recorded.
    def entries(lifts, resolved, locked)
      raise "No patch pin was lifted; retire or retarget the pins-lifted canary lane" if lifts.empty?

      lifts.sort_by { |lift| [lift.package, lift.name] }.map do |lift|
        version = resolved.fetch(lift.name) { raise "Lifted dependency #{lift.name} is missing from the bundle" }
        check_locked!(lift, locked.fetch([lift.package, lift.name], nil))
        [lift, version, placement(lift, version)]
      end
    end

    def placement(lift, version)
      lift.original.satisfied_by?(version) ? "within the pin" : "beyond the pin"
    end

    def check_locked!(lift, recorded)
      return if recorded && recorded.requirements.sort == lift.lifted.requirements.sort

      raise "Canary lock drift: #{lift.package} records #{lift.name} #{recorded || 'nothing'}, expected #{lift.lifted}"
    end

    def lines(entries, resolved)
      lifted = entries.map do |lift, version, place|
        "lifted #{lift.package} #{lift.name} #{lift.original} -> #{lift.lifted}: resolved #{version}, #{place}"
      end
      [*lifted, "#{STACK_HEADING}:", *stack(resolved).map { |name, version| "  #{name} #{version}" }]
    end

    def markdown(package, entries, resolved)
      rows = entries.map do |lift, version, place|
        "| #{lift.package} | #{lift.name} | `#{lift.original}` | `#{lift.lifted}` | #{version} | #{place} |"
      end
      versions = stack(resolved).map { |name, version| "#{name} #{version}" }.join(", ")
      ["### Pins-lifted canary report: #{package}", "",
       "| Package | Dependency | Pin | Lifted | Resolved | Versus pin |", "| --- | --- | --- | --- | --- | --- |",
       *rows, "", "#{STACK_HEADING}: #{versions}", ""].join("\n")
    end

    def stack(resolved)
      STACK.filter_map { |name| [name, resolved.fetch(name)] if resolved.key?(name) }
    end

    # The requirement each local package's dependency carries in the lock.
    def locked(lockfile)
      lockfile.specs.select { |spec| DependencyFloors.local?(spec.name) }.flat_map do |spec|
        spec.dependencies.map { |dependency| [[spec.name, dependency.name], dependency.requirement] }
      end.to_h
    end

    # Prints and summarizes a loaded canary bundle. Runs under `bundle exec`.
    def print!(specs, lockfile)
      resolved = specs.to_h { |spec| [spec.name, spec.version] }
      found = entries(DependencyCanary.lifts.values, resolved, locked(lockfile))
      puts lines(found, resolved)
      DependencyCanary.append_summary(markdown(File.basename(Dir.pwd), found, resolved))
    end
  end
end

if $PROGRAM_NAME == __FILE__
  require "bundler"
  abort "Run with #{DependencyCanary::ENVIRONMENT}=1 under the canary bundle" unless DependencyCanary.enabled?
  abort "Not running under a canary wrapper: #{ENV.fetch('BUNDLE_GEMFILE', nil)}" unless
    File.basename(Bundler.default_gemfile.to_s) == "Gemfile.canary"
  begin
    lockfile = Bundler::LockfileParser.new(Bundler.read_file(Bundler.default_lockfile))
    DependencyCanary::Report.print!(Bundler.load.specs, lockfile)
  rescue RuntimeError => e
    # The driver reports the last output line, so end with the reason, not a backtrace.
    abort e.message
  end
end
