# frozen_string_literal: true

module ConnectRPC
  module Generator
    class Renderer
      def initialize(schema, file)
        @schema = schema
        @file = file
      end

      def render
        @lines = ["# frozen_string_literal: true", "", "# Generated by protoc-gen-connectrpc-ruby. DO NOT EDIT!",
                  "# source: #{@file.name}", "", 'require "connectrpc"']
        required_files.each { |name| @lines << "require #{"#{Names.stem(name)}_pb".dump}" }
        @lines << ""
        namespace = Names.namespace(@file)
        namespace.each_with_index { |name, index| line(index, "module #{name}") }
        @file.service.each_with_index do |service, index|
          line(namespace.size, "") if index.positive?
          render_service(service, namespace.size)
        end
        namespace.size.times { |index| line(namespace.size - index - 1, "end") }
        "#{@lines.join("\n")}\n"
      end

      private

      def required_files
        methods = @file.service.flat_map { |service| service["method"] }
        types = methods.flat_map { |method| [method.input_type, method.output_type] }
        [@file.name, *types.map { |type| @schema.types.fetch(type).first.name }.uniq.sort].uniq
      end

      def line(depth, text)
        @lines << (text.empty? ? "" : ("  " * depth) + text)
      end

      def render_service(service, depth)
        line(depth, "module #{Names.rubify(service.name)}")
        depth += 1
        methods = service["method"].map { |method| [method, Names.rpc(method.name)] }
        constants = ["SERVICE", "Client", *methods.map { |_method, ruby| ruby.upcase }]
        line(depth, "%w[#{constants.join(' ')}].each do |name|")
        line(depth + 1, "next unless const_defined?(name, false)")
        line(depth, "")
        line(depth + 1, "raise ::ArgumentError, \"Generated service constant already defined: \#{self}::\#{name}\"")
        line(depth, "end")
        methods.each { |method, ruby| render_method(service, method, ruby, depth) }
        name = [@file.package, service.name].reject(&:empty?).join(".")
        line(depth, "")
        line(depth, "SERVICE = ::ConnectRPC::Service.new(")
        line(depth + 1, "name: #{name.dump}, methods: [#{methods.map { |_m, ruby| ruby.upcase }.join(', ')}]")
        line(depth, ")")
        render_client(methods, depth)
        render_handlers(methods, depth)
        line(depth - 1, "end")
      end

      def render_method(service, method, ruby, depth)
        name = [@file.package, service.name].reject(&:empty?).join(".")
        line(depth, "")
        line(depth, "#{ruby.upcase} = ::ConnectRPC::Method.new(")
        line(depth + 1, "service: #{name.dump}, name: #{method.name.dump},")
        render_type("request_type", method.input_type, depth + 1, comma: true)
        idempotency = { NO_SIDE_EFFECTS: :no_side_effects, IDEMPOTENT: :idempotent }[method.options&.idempotency_level]
        render_type("response_type", method.output_type, depth + 1, comma: !idempotency.nil?)
        line(depth + 1, "idempotency: :#{idempotency}") if idempotency
        line(depth, ")")
      end

      def render_type(keyword, type, depth, comma:)
        line(depth, "#{keyword}: ::Google::Protobuf::DescriptorPool.generated_pool.lookup(")
        line(depth + 1, type.delete_prefix(".").dump)
        line(depth, ").msgclass#{',' if comma}")
      end

      def render_client(methods, depth)
        line(depth, "")
        line(depth, "class Client")
        line(depth + 1, "def initialize(client:)")
        line(depth + 2, "@client = client")
        line(depth + 1, "end")
        methods.each do |entry|
          ruby = entry.last
          line(depth, "")
          line(depth + 1, "def #{ruby}(request, **options)")
          line(depth + 2, "@client.call(#{ruby.upcase}, request, **options)")
          line(depth + 1, "end")
        end
        line(depth, "end")
      end

      def render_handlers(methods, depth)
        keywords = methods.map { |_method, ruby| "#{ruby}:" }.join(", ")
        line(depth, "")
        line(depth, "def self.handlers#{"(#{keywords})" unless methods.empty?}")
        methods.each do |entry|
          ruby = entry.last
          line(depth + 1,
               "raise ::ArgumentError, #{"#{ruby} must respond to call".dump} unless #{ruby}.respond_to?(:call)")
        end
        line(depth, "") unless methods.empty?
        entries = methods.map { |_method, ruby| "#{ruby.upcase}.path => #{ruby}" }.join(", ")
        line(depth + 1, methods.empty? ? "{}" : "{ #{entries} }")
        line(depth, "end")
      end
    end
  end
end
