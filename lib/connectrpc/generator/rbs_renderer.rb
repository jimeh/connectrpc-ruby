# frozen_string_literal: true

module ConnectRPC
  module Generator
    class RBSRenderer
      def initialize(schema, file)
        @schema = schema
        @file = file
      end

      def render
        @lines = ["# Generated by protoc-gen-connectrpc-ruby. DO NOT EDIT!", "# source: #{@file.name}", ""]
        namespace = Names.namespace(@file)
        namespace.each_with_index { |name, index| line(index, "module #{name}") }
        @file.service.each { |service| render_service(service, namespace.size) }
        namespace.size.times { |index| line(namespace.size - index - 1, "end") }
        "#{@lines.join("\n")}\n"
      end

      private

      def line(depth, text)
        @lines << (("  " * depth) + text)
      end

      def types(method)
        [method.input_type, method.output_type].map { |type| @schema.ruby_types.fetch(type) }
      end

      def handler(method)
        request, reply = types(method)
        "(^(#{request}, ::ConnectRPC::Context) -> #{reply}) | ::ConnectRPC::_Handler[#{request}, #{reply}]"
      end

      def render_service(service, depth)
        line(depth, "module #{Names.rubify(service.name)}")
        methods = service["method"]
        methods.each do |method|
          line(depth + 1, "#{Names.rpc(method.name).upcase}: ::ConnectRPC::Method[#{types(method).join(', ')}]")
        end
        line(depth + 1, "SERVICE: ::ConnectRPC::Service")
        line(depth + 1, "class Client")
        line(depth + 2, "def initialize: (client: ::ConnectRPC::Client) -> void")
        methods.each do |method|
          request, reply = types(method)
          line(depth + 2, "def #{Names.rpc(method.name)}: (#{request} request, " \
                          "?metadata: ::ConnectRPC::metadata_input, ?timeout: ::Numeric?) -> ::ConnectRPC::Response[#{reply}]")
        end
        line(depth + 1, "end")
        keywords = methods.map { |method| "#{Names.rpc(method.name)}: (#{handler(method)})" }.join(", ")
        values = methods.map { |method| "::ConnectRPC::_Handler[#{types(method).join(', ')}]" }.uniq
        line(depth + 1,
             "def self.handlers: (#{keywords}) -> ::Hash[::String, #{values.empty? ? 'bot' : values.join(' | ')}]")
        line(depth, "end")
      end
    end
  end
end
