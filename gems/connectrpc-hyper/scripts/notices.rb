# frozen_string_literal: true

# Generates THIRD_PARTY_NOTICES.md from the locked crate graph: every crate
# compiled into the extension on any target platform (activated normal
# dependencies, without proc-macros and build-only crates), with its declared
# license and the license texts it ships. `--check` fails when the file is stale.
require "digest"
require "json"
require "open3"

package = File.expand_path("..", __dir__)
output, status = Open3.capture2("cargo", "metadata", "--locked", "--format-version", "1", chdir: package)
abort "cargo metadata failed" unless status.success?
packages = JSON.parse(output).fetch("packages").to_h { |entry| [[entry.fetch("name"), entry.fetch("version")], entry] }
# cargo tree reports activated dependencies; the lockfile also lists crates
# that only weak features name (ring, through rustls-webpki), which never build.
tree, status = Open3.capture2("cargo", "tree", "--locked", "--target", "all", "--edges", "normal,no-proc-macro",
                              "--prefix", "none", "--format", "{p}", chdir: package)
abort "cargo tree failed" unless status.success?
linked = tree.lines.filter_map { |line| line.split[0, 2] if line.split[1]&.start_with?("v") }.uniq
linked.reject! { |name, _| name == "connectrpc_hyper" }
crates = linked.map { |name, version| packages.fetch([name, version.delete_prefix("v")]) }
               .sort_by { |entry| [entry.fetch("name"), entry.fetch("version")] }
texts = {}
lines = ["# Third-party notices", "",
         "The connectrpc-hyper native extension links the following Rust crates, resolved from `Cargo.lock`. " \
         "Each crate's license texts follow its list entry by reference. Generated by `scripts/notices.rb`; " \
         "do not edit.", "", "## Crates", ""]
crates.each do |entry|
  directory = File.dirname(entry.fetch("manifest_path"))
  files = Dir.children(directory).grep(/\A(?:LICEN[CS]E|COPYING|NOTICE|COPYRIGHT)/i).sort
  references = files.map do |name|
    body = File.read(File.join(directory, name), mode: "rb").force_encoding(Encoding::UTF_8).scrub.strip
    key = Digest::SHA256.hexdigest(body)[0, 12]
    texts[key] ||= body
    "[#{name}](#text-#{key})"
  end
  license = entry["license"] || "see license file"
  lines << "- #{entry.fetch('name')} #{entry.fetch('version')} (#{license}): #{references.join(', ')}"
end
lines.push("", "## License texts", "")
texts.each do |key, body|
  lines.push("### text-#{key}", "", "```text", body, "```", "")
end
notices = "#{lines.join("\n").rstrip}\n"
path = File.join(package, "THIRD_PARTY_NOTICES.md")
if ARGV == ["--check"]
  abort "THIRD_PARTY_NOTICES.md is stale; run scripts/notices.rb" unless File.exist?(path) && File.read(path) == notices
  puts "Third-party notices match #{crates.size} linked crates"
else
  File.write(path, notices)
  puts "Wrote notices for #{crates.size} linked crates"
end
